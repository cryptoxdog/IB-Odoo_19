#!/usr/bin/env python3
"""Build PR description from commits and diff vs base branch."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

_TEMPLATE = Path(__file__).resolve().parents[1] / ".github" / "pull_request_template.md"


def _run(*args: str) -> str:
    return subprocess.check_output(args, text=True).strip()


def _section_body(template: str, heading: str) -> str:
    marker = f"## {heading}\n"
    start = template.find(marker)
    if start < 0:
        raise ValueError(f"pull request template is missing {marker.strip()}")
    content_at = start + len(marker)
    next_heading = template.find("\n## ", content_at)
    if next_heading < 0:
        return template[content_at:]
    return template[content_at:next_heading]


def _replace_section(template: str, heading: str, body: str) -> str:
    marker = f"## {heading}\n"
    start = template.find(marker)
    if start < 0:
        raise ValueError(f"pull request template is missing {marker.strip()}")
    content_at = start + len(marker)
    next_heading = template.find("\n## ", content_at)
    filled = "\n" + body.strip("\n") + "\n"
    if next_heading < 0:
        return template[:content_at] + filled
    return template[:content_at] + filled + template[next_heading:]


def fill_template(template: str, *, commits: str, stat: str) -> str:
    """Fill Summary and Changes. Leave every other section, including Test plan, as written."""
    for heading in ("Summary", "Changes", "Test plan"):
        _section_body(template, heading)
    changes = f"```\n{stat.rstrip()}\n```"
    filled = _replace_section(template, "Summary", commits.strip())
    return _replace_section(filled, "Changes", changes)


def _fallback_body(base: str, commits: str, stat: str) -> str:
    return f"""## Summary
{commits}

## Changes
```
{stat}
```

## Test plan
- [ ] CI Gate (`ci.yml`) green
- [ ] Odoo.sh checks (if applicable)
- [ ] Module upgrade validated on staging if schema changed

---
_Auto-generated by `make pr` (github publication kernel) → base `{base}`._
"""


def build_body(base: str) -> str:
    title = _run("git", "log", "-1", "--pretty=%s")
    try:
        commits = _run("git", "log", f"origin/{base}..HEAD", "--pretty=format:- %s")
    except subprocess.CalledProcessError:
        commits = f"- {title}"
    if not commits:
        commits = f"- {title}"
    try:
        stat = _run("git", "diff", f"origin/{base}...HEAD", "--stat")
    except subprocess.CalledProcessError:
        stat = _run("git", "show", "--stat", "--oneline", "-1")

    if not _TEMPLATE.is_file():
        return _fallback_body(base, commits, stat)
    template = _TEMPLATE.read_text(encoding="utf-8")
    return fill_template(template, commits=commits, stat=stat)


def main() -> int:
    base = sys.argv[1] if len(sys.argv) > 1 else "Staging"
    print(build_body(base))
    return 0


if __name__ == "__main__":
    sys.exit(main())
