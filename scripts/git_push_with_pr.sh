#!/usr/bin/env bash
# Push the current HEAD only after live L4 check-remote allows this worktree.
# Prove origin's branch ref matches local HEAD. Does not open the PR.
#
# This script owns the publication gate. It runs on every attempt, before
# git push, including retries where git has nothing new to push and the
# pre-push stage runs no hook. After it passes, the push alone carries
# L9_PUBLISH_VALIDATED_SHA / L9_PUBLISH_TARGET / L9_PUBLISH_PID (this shell's PID),
# which scripts/pre_push_validate.sh honours only for exactly this push and only
# while this process is its live ancestor, so the candidate is validated once.
set -euo pipefail

# A binding is set below, on the push only, after this gate. Never inherit one.
unset L9_PUBLISH_VALIDATED_SHA L9_PUBLISH_TARGET L9_PUBLISH_PID

refuse() {
  echo "refusing to publish: $*" >&2
  exit 1
}

require_l4_release() {
  # These switches make upstream release_allows_remote() return success.
  # They are not authorization for this publication.
  local l4_switch="${L9_L4_LOCAL_AUTONOMY-1}"
  case "${l4_switch}" in
    0|false|False|no)
      refuse "L9_L4_LOCAL_AUTONOMY=${l4_switch} is not release authorization"
      ;;
  esac
  if [[ -n "${L9_LOCAL_PUSH_AUTHORIZED:-}" ]]; then
    refuse "L9_LOCAL_PUSH_AUTHORIZED is not release authorization"
  fi

  local resolver="${HOME}/.cursor-governance/ops/scripts/resolve_governance_paths.sh"
  if [[ ! -f "${resolver}" ]]; then
    refuse "L4 provider is not available (no governance resolver at \$HOME/.cursor-governance)"
  fi
  # shellcheck disable=SC1090
  source "${resolver}"
  if ! resolve_governance_paths; then
    refuse "L4 provider is not available at \$HOME/.cursor-governance"
  fi
  local l4_py="${GOV_ROOT}/ops/autonomy/l4_local.py"
  if [[ ! -f "${l4_py}" ]]; then
    refuse "L4 check-remote provider is missing"
  fi

  local worktree gov_real l4_out l4_rc
  worktree="$(git rev-parse --show-toplevel)"
  worktree="$(python3 -c 'import os,sys; print(os.path.realpath(sys.argv[1]))' "${worktree}")"
  gov_real="$(python3 -c 'import os,sys; print(os.path.realpath(sys.argv[1]))' "${GOV_ROOT}")"
  if [[ "${worktree}" == "${gov_real}" ]]; then
    refuse "L4 workspace resolved to the governance checkout"
  fi

  set +e
  l4_out="$(python3 "${l4_py}" check-remote --workspace "${worktree}")"
  l4_rc=$?
  set -e
  printf '%s\n' "${l4_out}"
  if [[ "${l4_rc}" -ne 0 ]]; then
    refuse "L4 check-remote denied release for ${worktree} (exit ${l4_rc})"
  fi
  printf '%s' "${l4_out}" | python3 -c '
import json, sys
data = json.load(sys.stdin)
if data.get("allowed") is not True or not isinstance(data.get("reason"), str) or not data["reason"]:
    raise SystemExit("L4 check-remote did not return release authorization")
'
}

# The push must run the repository's pre-push stage (.pre-commit-config.yaml,
# including gitleaks-push). Absent, disabled, or foreign hooks refuse here;
# later CI is not local enforcement.
require_pre_push_enforcement() {
  local hooks_dir hook
  if [[ -n "${SKIP:-}" ]]; then
    refuse "SKIP is set; pre-push hooks may not be skipped"
  fi
  if [[ ! -f .pre-commit-config.yaml ]]; then
    refuse ".pre-commit-config.yaml is missing"
  fi
  hooks_dir="$(git rev-parse --path-format=absolute --git-path hooks)" \
    || refuse "cannot resolve the effective git hooks directory"
  hook="${hooks_dir}/pre-push"
  if [[ ! -f "${hook}" || ! -x "${hook}" ]]; then
    refuse "no executable pre-push hook at ${hook}; run: pre-commit install --hook-type pre-push"
  fi
  if ! grep -qxF '# File generated by pre-commit: https://pre-commit.com' "${hook}" \
    || ! grep -qxF 'ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=pre-push)' "${hook}"; then
    refuse "${hook} is not the pre-commit pre-push hook for .pre-commit-config.yaml; run: pre-commit install --hook-type pre-push"
  fi
}

if [[ "${1:-}" == "--check-l4" ]]; then
  require_l4_release
  exit 0
fi

TARGET="${1:?target branch required}"
case "${TARGET}" in
  Staging|Production|staging|production)
    refuse "${TARGET} is a protected branch"
    ;;
esac

status="$(git status --porcelain)"
if [[ -n "${status}" ]]; then
  echo "refusing to publish: working tree, index, or untracked files are not clean" >&2
  printf '%s\n' "${status}" >&2
  exit 1
fi
LOCAL_SHA="$(git rev-parse HEAD)"

push_urls=()
while IFS= read -r push_url; do
  [[ -n "${push_url}" ]] && push_urls+=("${push_url}")
done < <(git remote get-url --push --all origin 2>/dev/null || true)
if [[ "${#push_urls[@]}" -ne 1 ]]; then
  refuse "origin must have exactly one push URL"
fi
python3 - "${push_urls[0]}" <<'PY'
import sys

url = sys.argv[1].removesuffix(".git")
allowed = {
    "https://github.com/cryptoxdog/IB-Odoo_19",
    "git://github.com/cryptoxdog/IB-Odoo_19",
    "git@github.com:cryptoxdog/IB-Odoo_19",
    "ssh://git@github.com/cryptoxdog/IB-Odoo_19",
}
if url not in allowed:
    raise SystemExit(f"refusing to publish: origin push URL is not cryptoxdog/IB-Odoo_19 ({sys.argv[1]})")
PY

export GH_REPO="cryptoxdog/IB-Odoo_19"
case "${PR_CHECK_SKIP_REMOTE:-0}" in
  1|true|True|yes) refuse "PR_CHECK_SKIP_REMOTE is set" ;;
esac
SMOKE_BYPASS=0
PR_SMOKE_BYPASS="${PR_SMOKE_BYPASS:-}"
if [[ -n "${PR_SMOKE_BYPASS// /}" ]]; then
  SMOKE_BYPASS=1
  echo "⚠️  install-smoke BYPASSED by operator: ${PR_SMOKE_BYPASS}" >&2
else
  case "${PR_CHECK_SKIP_SMOKE:-0}" in
    1|true|True|yes) refuse "PR_CHECK_SKIP_SMOKE is set (use make pr-nosmoke reason=...)" ;;
  esac
fi
case "${PR_CHECK_FORCE_SMOKE:-0}" in
  1|true|True|yes) refuse "PR_CHECK_FORCE_SMOKE is set" ;;
esac
require_pre_push_enforcement

if ! command -v gitleaks >/dev/null 2>&1; then
  refuse "gitleaks is not on PATH"
fi
if ! gitleaks detect --config .gitleaks.toml --redact --exit-code 2; then
  refuse "gitleaks detect failed"
fi

if [[ "${SMOKE_BYPASS}" != "1" ]] && ! bash scripts/install_smoke.sh --resolve; then
  refuse "install-smoke --resolve rejected the effective module lists"
fi

# Leave PR_SMOKE_BYPASS set. pr_check_run.sh skips Docker while it is set, then
# clears it before the rest of the gate.
if ! make pr-check; then
  refuse "make pr-check failed"
fi

if [[ "$(git rev-parse HEAD)" != "${LOCAL_SHA}" ]] || [[ -n "$(git status --porcelain)" ]]; then
  refuse "HEAD or the worktree changed during validation"
fi
# make pr-check's receipt decides the recheck. A change that reaches no addon
# or installer input needs no recheck. No receipt (a failed scope) means
# recheck. An operator bypass skips the recheck even when the receipt asks.
smoke_needed() {
  python3 - .cache/pr-check/scope.json <<'PY'
import json
import sys
try:
    needed = json.load(open(sys.argv[1])).get("smoke", 1)
except (OSError, ValueError, AttributeError):
    needed = 1
sys.exit(0 if needed else 1)
PY
}
if [[ "${SMOKE_BYPASS}" != "1" ]] && smoke_needed && ! bash scripts/install_smoke.sh --recheck; then
  refuse "install-smoke --recheck rejected the live evidence"
fi

# Second L4 check, at the push boundary: after validation, before any remote
# ref can move (the first runs in make_push_pipeline.sh before local work).
require_l4_release

# Push the validated commit, never the moving HEAD, as exactly one refspec.
# The pre-push stage still runs; the binding lets it skip only what this gate
# already did for this SHA and target. A nonzero hook exit fails the push and
# no remote ref advances.
set +e
# git push runs as a child (no exec), so this shell stays the hook's ancestor.
L9_PUBLISH_VALIDATED_SHA="${LOCAL_SHA}" L9_PUBLISH_TARGET="${TARGET}" L9_PUBLISH_PID="$$" \
  git push origin "${LOCAL_SHA}:refs/heads/${TARGET}"
push_rc=$?
set -e
if [[ "${push_rc}" -ne 0 ]]; then
  echo "git push failed (exit ${push_rc}) for origin/${TARGET} (validated ${LOCAL_SHA}); see the git and hook output above" >&2
  echo "Publication stays on make pr. An API push is not a fallback ceremony." >&2
  exit 1
fi

REMOTE_SHA="$(git ls-remote --heads origin "${TARGET}" | awk 'NR == 1 { print $1 }')"
if [[ -z "${REMOTE_SHA}" ]]; then
  echo "remote refs/heads/${TARGET} is missing after push; local HEAD is ${LOCAL_SHA}" >&2
  exit 1
fi
if [[ "${REMOTE_SHA}" != "${LOCAL_SHA}" ]]; then
  echo "remote refs/heads/${TARGET} is ${REMOTE_SHA}; local HEAD is ${LOCAL_SHA}" >&2
  exit 1
fi
echo "✅ Push complete → origin/${TARGET} (${LOCAL_SHA})"
